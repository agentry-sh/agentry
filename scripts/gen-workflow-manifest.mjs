#!/usr/bin/env node
// Read the repository-native workflows/**/*.md collection,
// extract structured workflow metadata (applies_to, required_events, etc.),
// and emit a typed TS manifest. The API uses this as answer-contract source
// material; these repository workflows are not executable query endpoints.
//
// Run automatically via `predev` / `predeploy` in apps/api/package.json.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import {
  listWorkflowFiles,
  parseWorkflowMarkdown,
  workflowRelativePath,
} from "./lib/workflow-files.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");
const outPath = join(repoRoot, "apps/api/src/workflow-manifest.generated.ts");
const checkOnly = process.argv.includes("--check");

const workflows = [];
for (const file of listWorkflowFiles()) {
  const raw = readFileSync(file, "utf8");
  const fm = parseWorkflowMarkdown(raw).data;
  const relativePath = workflowRelativePath(file);
  workflows.push({
    id: basename(file, ".md"),
    title: fm.title ?? "",
    description: fm.description ?? "",
    // Starter request used by agents as an adaptation seed. It is not a
    // workflow script; agents must map it to the project's live signals.
    starter_prompt: fm.starter_prompt ?? fm.prompt ?? "",
    difficulty: fm.difficulty ?? "",
    time_to_value: fm.time_to_value ?? "",
    category: fm.category ?? "",
    tags: fm.tags ?? [],
    prereqs: fm.prereqs ?? [],
    related: fm.related ?? [],
    applies_to: fm.applies_to ?? [],
    requires_revenue: fm.requires_revenue === true,
    requires_b2b: fm.requires_b2b === true,
    requires_two_sided: fm.requires_two_sided === true,
    required_events: fm.required_events ?? [],
    readiness_events:
      Array.isArray(fm.readiness_events) && fm.readiness_events.length > 0
        ? fm.readiness_events
        : (fm.required_events ?? []),
    required_event_properties: fm.required_event_properties ?? {},
    negative_fit: fm.negative_fit ?? [],
    ask_if_missing: fm.ask_if_missing ?? [],
    example_only: fm.example_only === true,
    execution_mode: fm.execution_mode ?? "on_demand",
    automation_playbook_id: fm.automation_playbook_id ?? null,
    automation_playbook_version: fm.automation_playbook_version ?? null,
    required_resources: fm.required_resources ?? [],
    published_at: fm.publishedAt ? new Date(fm.publishedAt).toISOString() : "",
    updated_at: fm.updatedAt ? new Date(fm.updatedAt).toISOString() : null,
    featured: fm.featured === true,
    url: `https://github.com/agentry-sh/agentry/blob/main/${relativePath}`,
  });
}

const body = `// AUTO-GENERATED by scripts/gen-workflow-manifest.mjs from workflows/**/*.md.
// Do NOT edit by hand — re-run \`node scripts/gen-workflow-manifest.mjs\` instead.
//
// This is the API's machine-readable view of the repository workflow
// collection. Planner and verify code may use it as answer-contract source
// material, but these entries are not executable API recipes.

export type AppShape =
  | "b2c-saas"
  | "b2b-saas"
  | "ecommerce"
  | "marketplace"
  | "content-media"
  | "devtools-api"
  | "games"
  | "internal-tool"
  | "single-purchase"
  | "open-source"
  | "enterprise-sales"
  | "mobile-app"
  | "universal";

export interface WorkflowManifestEntry {
  id: string;
  title: string;
  description: string;
  starter_prompt: string;
  difficulty: string;
  time_to_value: string;
  category: string;
  tags: string[];
  prereqs: string[];
  related: string[];
  applies_to: AppShape[];
  requires_revenue: boolean;
  requires_b2b: boolean;
  requires_two_sided: boolean;
  required_events: string[];
  readiness_events: string[];
  required_event_properties: Record<string, string[]>;
  negative_fit: string[];
  ask_if_missing: string[];
  example_only: boolean;
  execution_mode: "on_demand" | "human_review" | "automation_template";
  automation_playbook_id: "error-to-draft-pr" | "weekly-funnel-review" | null;
  automation_playbook_version: string | null;
  required_resources: string[];
  published_at: string;
  updated_at: string | null;
  featured: boolean;
  url: string;
}

export const WORKFLOW_MANIFEST: WorkflowManifestEntry[] = ${JSON.stringify(workflows, null, 2)};

export const WORKFLOW_MANIFEST_COUNT = ${workflows.length};
`;

if (checkOnly) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (current !== body) {
    console.error(
      "gen-workflow-manifest: generated manifest is stale. Run `node scripts/gen-workflow-manifest.mjs`.",
    );
    process.exit(1);
  }
  console.log(`gen-workflow-manifest: ${workflows.length} entries are in sync`);
} else {
  writeFileSync(outPath, body);
  console.log(`gen-workflow-manifest: wrote ${workflows.length} entries → ${outPath}`);
}
