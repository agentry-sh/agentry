#!/usr/bin/env node

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  listWorkflowFiles,
  workflowRelativePath,
} from "./lib/workflow-files.mjs";

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(
  repositoryRoot,
  "apps/redirect/src/workflow-routes.generated.ts",
);
const checkOnly = process.argv.includes("--check");

const routes = {};
for (const path of listWorkflowFiles()) {
  const slug = basename(path, ".md");
  if (routes[slug]) throw new Error(`duplicate workflow slug: ${slug}`);
  routes[slug] = workflowRelativePath(path);
}

const body = `// AUTO-GENERATED by scripts/gen-workflow-redirects.mjs.
// Do not edit by hand. This preserves backlinks from retired workflow URLs.

export const LEGACY_WORKFLOW_PATHS: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(routes, null, 2)});
`;

if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (current !== body) {
    console.error(
      "gen-workflow-redirects: generated routes are stale. Run `node scripts/gen-workflow-redirects.mjs`.",
    );
    process.exit(1);
  }
  console.log(`gen-workflow-redirects: ${Object.keys(routes).length} routes are in sync`);
} else {
  writeFileSync(outputPath, body);
  console.log(`gen-workflow-redirects: wrote ${Object.keys(routes).length} routes`);
}
